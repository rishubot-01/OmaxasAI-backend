
from django.contrib import admin

from .models import AIRequest, EvaluationResult, ModelRegistry


@admin.register(ModelRegistry)
class ModelRegistryAdmin(admin.ModelAdmin):
    """Manage external and self-hosted AI model configurations."""

    list_display = (
        "name",
        "provider",
        "model_id",
        "backend_type",
        "active",
        "priority",
        "supports_vision",
        "supports_tools",
    )

    list_filter = (
        "provider",
        "backend_type",
        "active",
        "supports_streaming",
        "supports_vision",
        "supports_tools",
    )

    search_fields = (
        "name",
        "model_id",
        "provider",
    )

    list_editable = (
        "active",
        "priority",
    )

    readonly_fields = (
        "created_at",
        "updated_at",
    )

    ordering = ("priority", "name")


@admin.register(AIRequest)
class AIRequestAdmin(admin.ModelAdmin):
    """View AI request activity without changing request records."""

    list_display = (
        "request_id",
        "user",
        "provider",
        "model_name",
        "task_category",
        "requested_mode",
        "status",
        "response_time_ms",
        "created_at",
    )

    list_filter = (
        "status",
        "task_category",
        "requested_mode",
        "provider",
        "web_search_used",
        "fallback_used",
    )

    search_fields = (
        "user__email",
        "provider",
        "model_name",
        "error_code",
    )

    ordering = ("-created_at",)
    list_select_related = ("user", "selected_model")
    date_hierarchy = "created_at"

    readonly_fields = tuple(
        field.name for field in AIRequest._meta.fields
    )

    def has_add_permission(self, request):
        """AI request records should be created by the application."""
        return False

    def has_delete_permission(self, request, obj=None):
        """Preserve operational history through the admin panel."""
        return False


@admin.register(EvaluationResult)
class EvaluationResultAdmin(admin.ModelAdmin):
    """Review benchmark results for registered AI models."""

    list_display = (
        "model",
        "benchmark_name",
        "task_category",
        "score",
        "passed",
        "latency_ms",
        "evaluated_at",
    )

    list_filter = (
        "task_category",
        "passed",
        "benchmark_name",
    )

    search_fields = (
        "model__name",
        "model__model_id",
        "benchmark_name",
        "result_summary",
    )

    list_select_related = ("model",)
    date_hierarchy = "evaluated_at"
    ordering = ("-evaluated_at",)

    readonly_fields = tuple(
        field.name for field in EvaluationResult._meta.fields
    )

    def has_add_permission(self, request):
        """Evaluation records should be generated by evaluation services."""
        return False

    def has_delete_permission(self, request, obj=None):
        return False
